#!/usr/bin/env python3
"""Generate portable Gherkin case files from requirement Markdown."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS_DIR = ROOT / "requirements"
DEFAULT_OUTPUT_DIR = ROOT / "tests" / "requirement-cases" / "generated"


def parse_requirement(path: Path) -> tuple[str, str, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path.name}: missing YAML front matter")
    parts = text.split("---", 2)
    if len(parts) != 3:
        raise ValueError(f"{path.name}: unterminated YAML front matter")

    metadata: dict[str, str] = {}
    for line in parts[1].splitlines():
        if not line.strip():
            continue
        key, separator, value = line.partition(":")
        if not separator:
            raise ValueError(f"{path.name}: unsupported front matter line: {line}")
        metadata[key.strip()] = value.strip().strip("\"'")

    requirement_id = metadata.get("id", "")
    if not re.fullmatch(r"REQ-[A-Z0-9]+-\d+", requirement_id):
        raise ValueError(f"{path.name}: invalid or missing requirement ID")
    if path.stem != requirement_id:
        raise ValueError(f"{path.name}: filename must match {requirement_id}")
    status = metadata.get("status", "")
    if status not in {"proposed", "accepted", "retired"}:
        raise ValueError(f"{path.name}: status must be proposed, accepted, or retired")

    fence = chr(96) * 3
    pattern = rf"(?ms)^{fence}gherkin\s*\n(.*?)^{fence}\s*$"
    blocks = re.findall(pattern, parts[2])
    if status == "retired":
        return requirement_id, status, ""
    if not blocks:
        raise ValueError(f"{path.name}: no gherkin scenario block found")
    if any(not re.search(r"(?m)^Feature:\s*\S", block) for block in blocks):
        raise ValueError(f"{path.name}: each gherkin block must contain a Feature")
    combined = "\n\n".join(block.strip() for block in blocks)
    scenario_count = len(re.findall(r"(?m)^\s*Scenario(?: Outline)?:\s*\S", combined))
    scenario_ids = set(re.findall(r"@(AC-[A-Z0-9-]+)", combined))
    if scenario_count == 0 or len(scenario_ids) != scenario_count:
        raise ValueError(
            f"{path.name}: every Scenario needs one unique @AC-... tag"
        )
    if f"@{requirement_id}" not in combined:
        raise ValueError(f"{path.name}: Gherkin block must include @{requirement_id}")
    return requirement_id, status, combined


def render_case_file(requirement_id: str, status: str, source: Path, feature: str) -> str:
    relative_source = source.relative_to(ROOT).as_posix()
    return "\n".join(
        [
            f"# Generated from {relative_source}. Do not edit this file directly.",
            f"# Requirement: {requirement_id}",
            f"# Requirement status at generation: {status}",
            "",
            feature.rstrip(),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--id", help="generate one requirement ID; default is all requirements")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="generated feature directory",
    )
    args = parser.parse_args()

    if args.id and not re.fullmatch(r"REQ-[A-Z0-9]+-\d+", args.id):
        parser.error("--id must use REQ-AREA-123 format")
    paths = (
        [REQUIREMENTS_DIR / f"{args.id}.md"]
        if args.id
        else sorted(REQUIREMENTS_DIR.glob("REQ-*.md"))
    )
    if not paths or any(not path.is_file() for path in paths):
        print("No matching requirement files found.", file=sys.stderr)
        return 2

    parsed: list[tuple[Path, str, str, str]] = []
    try:
        for path in paths:
            requirement_id, status, feature = parse_requirement(path)
            parsed.append((path, requirement_id, status, feature))
    except ValueError as error:
        print(error, file=sys.stderr)
        return 2

    output_dir = args.output_dir
    if not output_dir.is_absolute():
        output_dir = ROOT / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    generated_count = 0
    for source, requirement_id, status, feature in parsed:
        output_path = output_dir / f"{requirement_id}.feature"
        if status == "retired":
            if output_path.exists():
                output_path.unlink()
                print(f"Removed retired case file {output_path.relative_to(ROOT)}")
            continue
        output_path.write_text(
            render_case_file(requirement_id, status, source, feature),
            encoding="utf-8",
        )
        scenario_count = len(re.findall(r"(?m)^\s*Scenario(?: Outline)?:\s*\S", feature))
        generated_count += scenario_count
        print(f"Wrote {output_path.relative_to(ROOT)} ({scenario_count} scenarios)")
    print(f"Generated {generated_count} scenarios from {len(parsed)} requirement file(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
